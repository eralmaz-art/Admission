/** Файл → {имя, тип, base64}. Фото пережимается до 1600px по длинной стороне
 *  (JPEG) прямо при выборе — отправка быстрая даже с планшетной камеры 12 Мп.
 *  PDF (сканер) уходит как есть. */
function файлВПакет(файл) {
  return new Promise((решить, отклонить) => {
    const читатель = new FileReader();
    читатель.onerror = () => отклонить(new Error('Не удалось прочитать файл ' + файл.name));
    if (файл.type === 'application/pdf') {
      читатель.onload = () => решить({
        имя: файл.name, тип: 'application/pdf',
        base64: String(читатель.result).split(',')[1]
      });
      читатель.readAsDataURL(файл);
      return;
    }
    читатель.onload = () => {
      const картинка = new Image();
      картинка.onload = () => {
        const макс = СЖАТИЕ_МАКС_СТОРОНА;
        const масштаб = Math.min(1, макс / Math.max(картинка.width, картинка.height));
        const холст = document.createElement('canvas');
        холст.width = Math.round(картинка.width * масштаб);
        холст.height = Math.round(картинка.height * масштаб);
        холст.getContext('2d').drawImage(картинка, 0, 0, холст.width, холст.height);
        const dataUrl = холст.toDataURL('image/jpeg', СЖАТИЕ_КАЧЕСТВО);
        решить({
          имя: файл.name.replace(/\.\w+$/, '') + '.jpg', тип: 'image/jpeg',
          base64: dataUrl.split(',')[1],
          превью: dataUrl
        });
      };
      картинка.onerror = () => отклонить(new Error('Файл не является изображением: ' + файл.name));
      картинка.src = String(читатель.result);
    };
    читатель.readAsDataURL(файл);
  });
}

