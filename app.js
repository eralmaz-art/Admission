// ══════════════ ОФЛАЙН-ОЧЕРЕДЬ (IndexedDB) ══════════════
function открытьБазу() {
  return new Promise((решить, отклонить) => {
    const заявка = indexedDB.open('школа_приёмная', 1);
    заявка.onupgradeneeded = () =>
      заявка.result.createObjectStore('очередь', { keyPath: 'ид', autoIncrement: true });
    заявка.onsuccess = () => решить(заявка.result);
    заявка.onerror = () => отклонить(заявка.error);
  });
}

function действиеВБазе(режим, работа) {
  return открытьБазу().then(база => new Promise((решить, отклонить) => {
    const транзакция = база.transaction('очередь', режим);
    const хранилище = транзакция.objectStore('очередь');
    const заявка = работа(хранилище);
    транзакция.oncomplete = () => { база.close(); решить(заявка && заявка.result); };
    транзакция.onerror = () => { база.close(); отклонить(транзакция.error); };
  }));
}

async function вОчередь(пакет, причина) {
  await действиеВБазе('readwrite', х => х.add({
    создано: new Date().toISOString(),
    статус: 'ожидает',
    ошибка: '',
    попытка: new Date().toISOString(),  // время последней попытки отправки
    причина: причина || '',             // почему семья оказалась/осталась в очереди
    пакет
  }));
  await обновитьОчередьВезде();
}

function всеИзОчереди() { return действиеВБазе('readonly', х => х.getAll()); }
function удалитьИзОчереди(ид) { return действиеВБазе('readwrite', х => х.delete(ид)); }
function обновитьЗапись(запись) { return действиеВБазе('readwrite', х => х.put(запись)); }

async function обновитьОчередьВезде() {
  const записи = await всеИзОчереди();
  const бейдж = $('бейджОчередь');
  бейдж.hidden = записи.length === 0;
  бейдж.textContent = записи.length;
  $('заголовокОчереди').textContent = 'Очередь: ' + записи.length +
    ' ' + склонение(записи.length, 'семья', 'семьи', 'семей');
  $('кнопкаОтправитьОчередь').disabled = записи.length === 0 || идётОтправкаОчереди;

  const список = $('списокОчереди');
  список.innerHTML = '';
  if (!записи.length) {
    список.innerHTML = '<p class="тихо">Очередь пуста.</p>';
    return;
  }
  записи.forEach(з => {
    const строка = document.createElement('div');
    строка.className = 'элемент-очереди';
    const когда = new Date(з.создано);
    строка.innerHTML =
      '<div class="инфо"><b>Семья от ' +
        когда.toLocaleDateString('ru-RU') + ' ' +
        когда.toLocaleTimeString('ru-RU', { hour: '2-digit', minute: '2-digit' }) + '</b>' +
        'документов: ' + (з.пакет.паспорт.length + з.пакет.свидетельства.length) +
        (з.пакет.телефон ? ' · ' + з.пакет.телефон : '') + '</div>' +
      '<div class="действия">' +
        '<span class="плашка' + (з.статус === 'ошибка' ? ' ошибка' : '') + '" data-ид="' + з.ид + '">' +
          (з.статус === 'отправляется' ? 'отправляется…' : з.статус === 'ошибка' ? 'ошибка' : 'ожидает') +
        '</span>' +
        '<button type="button" class="удалить-семью" title="Удалить семью"' +
          (з.статус === 'отправляется' ? ' disabled' : '') + '>🗑</button>' +
      '</div>';
    // причина ожидания: время и итог последней попытки (вместо вечного «ожидает»)
    let причина = '';
    if (з.статус === 'ошибка' && з.ошибка) причина = 'сервер отказал: ' + з.ошибка;
    else if (з.статус === 'ожидает' && з.причина) причина = з.причина;
    if (причина) {
      const почему = document.createElement('div');
      почему.className = 'тихо';
      const т = з.попытка ? new Date(з.попытка) : null;
      почему.textContent = (т ? 'попытка ' +
        т.toLocaleTimeString('ru-RU', { hour: '2-digit', minute: '2-digit' }) + ' — ' : '') + причина;
      строка.querySelector('.инфо').appendChild(почему);
    }
    строка.querySelector('.удалить-семью').addEventListener('click', async () => {
      if (!confirm('Семья будет удалена безвозвратно. Удалить из очереди?')) return;
      await удалитьИзОчереди(з.ид);
      await обновитьОчередьВезде();
      тост('Семья удалена из очереди.');
    });
    список.appendChild(строка);
  });
}

function склонение(н, один, два, пять) {
  const н100 = н % 100, н10 = н % 10;
  if (н100 > 10 && н100 < 20) return пять;
  if (н10 === 1) return один;
  if (н10 >= 2 && н10 <= 4) return два;
  return пять;
}

/** Пакеты уходят по одному; успех — удаление из очереди. Сбой сети —
 *  остановка до следующего online/запуска. Логический отказ сервера
 *  (например, сменили токен) — пакет остаётся с пометкой «ошибка». */
async function отправитьОчередь() {
  if (идётОтправкаОчереди || !navigator.onLine) return;
  идётОтправкаОчереди = true;
  try {
    const записи = await всеИзОчереди();
    for (const запись of записи) {
      запись.статус = 'отправляется';
      await обновитьЗапись(запись);
      await обновитьОчередьВезде();
      // прогресс в секундах прямо на карточке семьи (ждём до 300 сек)
      const старт = Date.now();
      const таймер = setInterval(() => {
        const плашка = document.querySelector('.плашка[data-ид="' + запись.ид + '"]');
        if (плашка) плашка.textContent =
          'отправляется… ' + Math.round((Date.now() - старт) / 1000) + ' сек';
      }, 1000);
      let ответ;
      try {
        ответ = await запрос('recognize', запись.пакет, ТАЙМАУТ_ОЧЕРЕДИ);
      } catch (ош) {
        clearInterval(таймер);
        запись.статус = 'ожидает'; // сеть пропала — попробуем в следующий раз
        запись.попытка = new Date().toISOString();
        запись.причина = ош.name === 'AbortError'
          ? 'сервер не ответил за ' + Math.round(ТАЙМАУТ_ОЧЕРЕДИ / 1000) + ' сек (таймаут)'
          : 'нет сети / обрыв соединения';
        await обновитьЗапись(запись);
        break;
      }
      clearInterval(таймер);
      if (ответ.ok) {
        await удалитьИзОчереди(запись.ид);
        тост('Семья из очереди отправлена: ID ' + ответ.родитель.ид + ' (' + ответ.родитель.статус + ')');
      } else {
        запись.статус = 'ошибка';
        запись.ошибка = ответ.ошибка;
        запись.попытка = new Date().toISOString();
        await обновитьЗапись(запись);
      }
      await обновитьОчередьВезде();
    }
  } finally {
    идётОтправкаОчереди = false;
    await обновитьОчередьВезде();
  }
}

// ══════════════ ВХОД ══════════════
async function войти() {
  const пароль = $('вводПароля').value;
  if (!пароль) return;
  if (await ша256(пароль) === ХЭШ_ПАРОЛЯ) {
    localStorage.setItem('шк_разблокировано', ХЭШ_ПАРОЛЯ); // смена пароля снимает разблокировку
    $('вводПароля').value = '';
    показатьОшибку('ошибкаВхода', '');
    открытьПриложение();
  } else {
    показатьОшибку('ошибкаВхода', 'Неверный пароль.');
  }
}

function открытьПриложение() {
  $('навСемья').hidden = false;
  $('навОчередь').hidden = false;
  сброситьФорму();
  показатьЭкран('экранСемья');
  отправитьОчередь(); // вдруг с прошлой смены остались неотправленные семьи
}

// ══════════════ ЗАПУСК ══════════════
function привязатьСобытия() {
  $('кнопкаВхода').addEventListener('click', войти);
  $('вводПароля').addEventListener('keydown', с => { if (с.key === 'Enter') войти(); });

  $('кнопкаЕщёРебёнок').addEventListener('click', добавитьРебёнка);
  $('переключательКомплект').querySelectorAll('button').forEach(б =>
    б.addEventListener('click', () => установитьКомплект(б.dataset.значение)));
  $('кнопкаОтправить').addEventListener('click', отправитьСемью);

  $('кнопкаПодтвердить').addEventListener('click', подтвердитьСемью);
  $('кнопкаПозже').addEventListener('click', сверитьПозже);
  $('кнопкаСледующая').addEventListener('click', () => показатьЭкран('экранСемья'));

  $('кнопкаОтправитьОчередь').addEventListener('click', отправитьОчередь);
  $('навОчередь').addEventListener('click', async () => {
    await обновитьОчередьВезде();
    показатьЭкран('экранОчередь');
  });
  $('навСемья').addEventListener('click', () => {
    if (!$('экранСверка').hidden &&
        !confirm('Уйти без подтверждения? Записи семьи останутся со статусом РАСПОЗНАНО.')) return;
    показатьЭкран('экранСемья');
  });

  window.addEventListener('online', () => {
    тост('Сеть появилась — отправляем очередь…');
    отправитьОчередь();
  });
  window.addEventListener('offline', () => тост('Сети нет. Семьи будут копиться в очереди.'));
}

async function запуск() {
  привязатьСобытия();
  await обновитьОчередьВезде();

  if ('serviceWorker' in navigator) {
    try { await navigator.serviceWorker.register('sw.js'); } catch (е) { /* file:// — не страшно */ }
  }

  if (localStorage.getItem('шк_разблокировано') === ХЭШ_ПАРОЛЯ) {
    открытьПриложение();
  } else {
    показатьЭкран('экранВход');
  }
}

