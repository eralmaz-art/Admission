/** POST на Web App. Тело — строка (text/plain): браузер шлёт без preflight,
 *  который Apps Script не обслуживает. Ответ всегда JSON {ok, …}. */
async function запрос(действие, данные, таймаутМс) {
  if (АДРЕС_СЕРВЕРА.indexOf('ВСТАВЬТЕ') === 0) throw new Error('В app.js не вставлен URL сервера.');
  const контроллер = new AbortController();
  const т = setTimeout(() => контроллер.abort(), таймаутМс || 60000);
  try {
    const ответ = await fetch(АДРЕС_СЕРВЕРА, {
      method: 'POST',
      body: JSON.stringify(Object.assign({ action: действие, токен: ТОКЕН }, данные)),
      signal: контроллер.signal
    });
    return await ответ.json();
  } finally {
    clearTimeout(т);
  }
}

