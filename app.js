/** Уникальный ид пакета: сервер по нему отсекает повторные доставки (дубли строк). */
function уникальныйИд() {
  return crypto.randomUUID ? crypto.randomUUID()
    : Date.now().toString(36) + '-' + Math.random().toString(36).slice(2);
}

/** Пакет семьи для recognize/очереди — ровно формат сервера Этапа 1
 *  плюс ид_пакета (идемпотентность: повтор с тем же ид не создаёт дублей). */
function собратьПакет() {
  const паспорт = [];
  слотыДокументов.forEach(с => {
    if ((с.ключ === 'паспорт1' || с.ключ === 'паспорт2') && с.пакет)
      паспорт.push({ имя: с.пакет.имя, тип: с.пакет.тип, base64: с.пакет.base64 });
  });
  const свидетельства = слотыДетей().filter(с => с.пакет)
    .map(с => ({ имя: с.пакет.имя, тип: с.пакет.тип, base64: с.пакет.base64 }));
  return {
    ид_пакета: уникальныйИд(),
    паспорт, свидетельства,
    телефон: $('вводТелефона').value.trim(),
    комплект: текущийКомплект(),
    примечание: $('вводПримечания').value.trim()
  };
}

// ══════════════ ОТПРАВКА СЕМЬИ ══════════════
async function отправитьСемью() {
  const паспорт1 = слотыДокументов.find(с => с.ключ === 'паспорт1');
  if (!паспорт1 || !паспорт1.пакет) {
    показатьОшибку('ошибкаОтправки', 'Паспорт — сторона 1 обязателен: снимите или выберите файл.');
    return;
  }
  показатьОшибку('ошибкаОтправки', '');
  const пакет = собратьПакет();

  // нет сети — сразу в очередь, приёмная не останавливается
  if (!navigator.onLine) {
    await вОчередь(пакет, 'нет сети');
    тост('Нет сети. Семья сохранена в очередь — отправится сама.', 5000);
    сброситьФорму();
    показатьЭкран('экранСемья');
    return;
  }

  начатьОжидание(пакет.свидетельства.length);
  let ответ;
  try {
    ответ = await запрос('recognize', пакет, ТАЙМАУТ_РАСПОЗНАВАНИЯ);
  } catch (ош) {
    // таймаут или обрыв — пакет в очередь, работаем дальше
    остановитьОжидание();
    await вОчередь(пакет, ош.name === 'AbortError'
      ? 'сервер не ответил (таймаут)' : 'нет сети / обрыв соединения');
    показатьЭкран('экранСемья');
    сброситьФорму();
    тост('Сервер не ответил. Сохранено, отправится позже.', 5000);
    return;
  }
  остановитьОжидание();

  if (!ответ.ok) {
    // логический отказ (например, токен) — очередь не поможет, форму сохраняем
    показатьЭкран('экранСемья');
    показатьОшибку('ошибкаОтправки', 'Сервер отказал: ' + ответ.ошибка);
    return;
  }

  текущийОтвет = ответ;
  построитьЭкранСверки(ответ);
  сброситьФорму();
  показатьЭкран('экранСверка');
}

// ══════════════ ЭКРАН «ОЖИДАНИЕ» ══════════════
function начатьОжидание(количествоСор) {
  показатьЭкран('экранОжидание');
  const этапы = [['Отправляем файлы…', 4], ['Распознаём паспорт…', 24]];
  for (let и = 1; и <= количествоСор; и++) этапы.push(['Распознаём СОР ' + и + '…', 22]);
  этапы.push(['Записываем в реестр…', 9999]);
  const старт = Date.now();
  таймерОжидания = setInterval(() => {
    const секунд = Math.round((Date.now() - старт) / 1000);
    $('секундыОжидания').textContent = секунд + ' сек';
    let накоплено = 0;
    for (const [текст, длительность] of этапы) {
      накоплено += длительность;
      if (секунд < накоплено) { $('этапОжидания').textContent = текст; break; }
    }
  }, 1000);
  $('этапОжидания').textContent = этапы[0][0];
  $('секундыОжидания').textContent = '0 сек';
}

function остановитьОжидание() {
  clearInterval(таймерОжидания);
  таймерОжидания = null;
}

