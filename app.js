function создатьСлот(ключ, название, обязателен, удаляем) {
  const узел = document.createElement('div');
  узел.className = 'слот';
  узел.innerHTML =
    '<div class="слот-верх">' +
      '<span class="слот-название">' + название + (обязателен ? ' <b class="обяз">*</b>' : '') + '</span>' +
      '<button type="button" class="слот-удалить" title="Убрать" ' + (удаляем ? '' : 'hidden') + '>✕</button>' +
    '</div>' +
    '<div class="слот-кнопки">' +
      '<label class="кнопка-слот">📷 Камера<input type="file" accept="image/*" capture="environment" hidden></label>' +
      '<label class="кнопка-слот">📁 Файл<input type="file" accept="image/*,application/pdf" hidden></label>' +
    '</div>' +
    '<div class="превью" hidden></div>';

  const слот = { ключ, пакет: null, узел };

  узел.querySelectorAll('input[type=file]').forEach(вход => {
    вход.addEventListener('change', async () => {
      const файл = вход.files[0];
      вход.value = ''; // тот же файл можно выбрать повторно
      if (!файл) return;
      if (файл.type === 'application/pdf' && файл.size > ПОРОГ_ТЯЖЁЛОГО_PDF) {
        тост('Тяжёлый файл может не отправиться — предпочтительнее фото камерой.', 6000);
      }
      try {
        слот.пакет = await файлВПакет(файл); // повторный выбор заменяет файл
        const превью = узел.querySelector('.превью');
        превью.hidden = false;
        превью.innerHTML = (слот.пакет.превью
            ? '<img src="' + слот.пакет.превью + '" alt="">'
            : '<div class="пдф">📄</div>') +
          '<span class="превью-имя">' + слот.пакет.имя + '</span>' +
          '<button type="button" class="превью-удалить" title="Убрать файл">✕</button>';
        превью.querySelector('.превью-удалить').addEventListener('click', () => {
          слот.пакет = null;
          превью.hidden = true;
          превью.innerHTML = '';
          узел.classList.remove('заполнен');
        });
        узел.classList.add('заполнен');
      } catch (ош) {
        слот.пакет = null;
        тост('Ошибка файла: ' + ош.message);
      }
    });
  });

  узел.querySelector('.слот-удалить').addEventListener('click', () => {
    слотыДокументов = слотыДокументов.filter(с => с !== слот);
    узел.remove();
    обновитьКнопкуЕщёРебёнок();
  });

  слотыДокументов.push(слот);
  return узел;
}

